CHANNELS = ["Online", "Retail"]
SPLIT = dt.date(2025, 3, 1)


def sales_rows() -> list[dict]:
    """720 rows: 60 dates x 4 regions x 3 products. Planted effects in the later
    period (from 2025-03-01): West sells far fewer units, and Gadget's price
    rises 10%. Everything else is steady."""
    rows = []
    day0 = dt.date(2025, 1, 1)
    for d in range(60):
        date = day0 + dt.timedelta(days=2 * d)
        later = date >= SPLIT
        for r, region in enumerate(REGIONS):
            for p, (product, (price, unit_cost)) in enumerate(PRODUCTS.items()):
                units = 10 + 2 * r + 3 * p + (d * 7 + r * 3 + p * 5) % 5
                if later and region == "West":
                    units = max(1, units - 9)
                if later and product == "Gadget":
                    price = round(price * 1.10, 2)
                rows.append({
                    "order_date": date.isoformat(), "region": region, "product": product,
                    "channel": CHANNELS[(d + r + p) % 2], "units": units, "unit_price": price,
                    "revenue": round(units * price, 2), "cost": round(units * unit_cost, 2),
                })
    return rows


def write_csv(path: Path, rows: list[dict], columns: list[str]) -> None:
    with open(path, "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=columns)
        w.writeheader()
        for row in rows:
            w.writerow({c: row[c] for c in columns})


